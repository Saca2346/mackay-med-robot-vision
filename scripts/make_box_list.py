"""Build a human-readable list of every box on the shelf: name, size, expiry, LOT, GTIN/REF and rack position.

Sources (read only, never modified):
  data/rak/inventaris.csv   boxes on the shelf (filled in by scripts/rak_inventaris.py, checked by a person)
  data/gtin_catalog.csv     GTIN -> product + size (only rows with verified = 1)
  data/rak/posisi.csv       rack / level / column per box (still an EXAMPLE until the team sends real positions)

Output: data/rak/box_list.csv and data/rak/box_list.md. Both stay out of git (hospital data; see .gitignore).
Run it again after every `rak_inventaris ambil/kembali`, so the list matches the shelf.

  python scripts/make_box_list.py
"""
from __future__ import annotations

import csv
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
INV, CAT, POS = ROOT / "data/rak/inventaris.csv", ROOT / "data/gtin_catalog.csv", ROOT / "data/rak/posisi.csv"
OUT_CSV, OUT_MD = ROOT / "data/rak/box_list.csv", ROOT / "data/rak/box_list.md"

STATUS = {"terverifikasi": "on shelf (verified)", "diambil": "taken", "belum_dipetakan": "not mapped yet"}
NAMES = {"ivascular": "iVascular", "orbusneich": "OrbusNeich", "apt medical": "APT Medical", "terumo": "Terumo",
         "boston scientific": "Boston Scientific", "nc emerge": "NC Emerge", "conqueror nc pro": "Conqueror NC Pro"}
FIELDS = ["box_id", "brand", "product", "size", "diameter_mm", "length_mm", "expiry", "lot", "gtin", "ref",
          "rack", "level", "column", "position_source", "status", "check"]


def num(s: str) -> str:
    """'2.50' -> '2.5', '' -> ''"""
    try:
        return f"{float(s):g}"
    except ValueError:
        return ""


def read(path: Path) -> list[dict]:
    with open(path, encoding="utf-8-sig", newline="") as f:
        return list(csv.DictReader(f))


def main() -> None:
    inv = read(INV)
    cat = {}
    for r in read(CAT):
        if r.get("verified", "").strip() == "1":
            cat[(r["product"].strip().lower(), num(r["diameter_mm"]), num(r["length_mm"]))] = r
    pos = {r["box_id"]: r for r in read(POS)} if POS.exists() else {}

    rows = []
    for b in sorted(inv, key=lambda r: r["box_id"]):
        d, L = num(b["diameter"]), num(b["length"])
        c = cat.get((b["product"].strip().lower(), d, L), {})
        p = pos.get(b["box_id"], {})
        check = []
        if "RECHECK" in (b.get("note") or ""):
            check.append("columns were auto-repaired: compare with the real box")
        if (b.get("sources") or "").startswith("USULAN 1 bukti"):
            check.append("identified from 1 evidence only")
        rows.append({
            "box_id": b["box_id"],
            "brand": NAMES.get(b["brand"].strip().lower(), b["brand"].title()),
            "product": NAMES.get(b["product"].strip().lower(), b["product"].title()),
            "size": f"{d} x {L} mm" if d and L else "no size",
            "diameter_mm": d, "length_mm": L,
            "expiry": b["expiry"], "lot": b["lot"],
            "gtin": b["gtin"] or c.get("gtin", ""), "ref": c.get("ref", ""),
            "rack": p.get("rak", ""), "level": p.get("level", ""), "column": p.get("kolom", ""),
            "position_source": {"contoh": "EXAMPLE"}.get(p.get("sumber", ""), p.get("sumber", "")),
            "status": STATUS.get(b["status"], b["status"]),
            "check": "; ".join(check),
        })

    with open(OUT_CSV, "w", encoding="utf-8", newline="") as f:
        w = csv.DictWriter(f, fieldnames=FIELDS)
        w.writeheader()
        w.writerows(rows)

    # same product + size more than once -> only expiry / LOT tells the boxes apart
    groups: dict[tuple, list[str]] = {}
    for r in rows:
        groups.setdefault((r["product"], r["size"]), []).append(r["box_id"])
    twins = {k: v for k, v in groups.items() if len(v) > 1}

    cols = ["box_id", "brand", "product", "size", "expiry", "lot", "gtin", "ref", "rack", "level", "column",
            "status", "check"]
    md = ["# Box list", "",
          f"Generated by `scripts/make_box_list.py` from `inventaris.csv`, `gtin_catalog.csv` and `posisi.csv`. "
          f"{sum(r['status'].startswith('on shelf') for r in rows)} of {len(rows)} boxes are on the shelf.", "",
          "Rack / level / column are an **EXAMPLE** until the team sends the real position file. "
          "An empty expiry or LOT means it is not recorded yet.", "",
          "| " + " | ".join(cols) + " |", "|" + " --- |" * len(cols)]
    md += ["| " + " | ".join(r[c] or "–" for c in cols) + " |" for r in rows]
    if twins:
        md += ["", "## Identical boxes (same product and size)", "",
               "These boxes look the same; only the printed expiry date (and LOT) tells them apart. "
               "FEFO picks the earliest expiry, so the camera must read the date to pick the right box.", ""]
        for (prod, size), ids in twins.items():
            exp = ", ".join(f"{i} {next(r['expiry'] for r in rows if r['box_id'] == i) or '?'}" for i in ids)
            md.append(f"- {prod} ({size}): {exp}")
    OUT_MD.write_text("\n".join(md) + "\n", encoding="utf-8")
    print(f"{len(rows)} boxes -> {OUT_CSV.relative_to(ROOT)}, {OUT_MD.relative_to(ROOT)}")


if __name__ == "__main__":
    sys.exit(main())
